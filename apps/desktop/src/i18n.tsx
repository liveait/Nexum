export type MessageKey = keyof typeof zhCN;
export function isMessageKey(value: string): value is MessageKey {
  return Object.prototype.hasOwnProperty.call(zhCN, value);
}

export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string;

export function resolveLocale(preference: LanguagePreference): Locale {
  if (preference !== "system") return preference;
  const preferred = navigator.languages?.[0] ?? navigator.language;
  return preferred?.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function translate(locale: Locale, key: MessageKey, values: Record<string, string | number> = {}): string {
  const message = locale === "zh-CN" ? zhCN[key] : key;
  return message.replace(/\{(\w+)\}/g, (match, name: string) => values[name]?.toString() ?? match);
}

const TranslationContext = createContext<Translate>((key, values) => translate("en", key, values));

export function TranslationProvider({ translateMessage, children }: { translateMessage: Translate; children: ReactNode }) {
  return <TranslationContext.Provider value={translateMessage}>{children}</TranslationContext.Provider>;
}

export function useTranslation(): Translate {
  return useContext(TranslationContext);
}
